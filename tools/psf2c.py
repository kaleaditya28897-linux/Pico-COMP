#!/usr/bin/env python3
"""Convert a PSF1 console font (with Unicode table) to a CP437-ordered C array.

Usage: tools/psf2c.py /usr/share/kbd/consolefonts/ter-v16n.psf.gz firmware/common/font8x16.c
Terminus is licensed under the SIL Open Font License 1.1.
"""
import gzip
import sys

# Glyphs for CP437 control codes 0x01-0x1F and 0x7F (the IBM PC graphic symbols).
LOW = "\0☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"


# Block elements missing from Terminus, synthesised.
SYNTH = {
    0xDC: bytes(8) + b"\xff" * 8,
    0xDD: b"\xf0" * 16,
    0xDE: b"\x0f" * 16,
    0xDF: b"\xff" * 8 + bytes(8),
    0xB2: bytes([0xdd, 0x77] * 8),
}


def load_psf1(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    assert data[:2] == b"\x36\x04", "not a PSF1 font"
    mode, height = data[2], data[3]
    count = 512 if mode & 1 else 256
    glyphs = [data[4 + i * height: 4 + (i + 1) * height] for i in range(count)]
    table = {}
    if mode & 2:
        pos = 4 + count * height
        for g in range(count):
            while True:
                (v,) = struct_u16(data, pos)
                pos += 2
                if v == 0xFFFF:
                    break
                if v == 0xFFFE:      # start of a combining sequence: ignore the rest
                    while struct_u16(data, pos)[0] != 0xFFFF:
                        pos += 2
                    continue
                table.setdefault(v, g)
    return glyphs, table, height


def struct_u16(data, pos):
    return (data[pos] | data[pos + 1] << 8,)


def cp437_char(b):
    if 1 <= b <= 31:
        return LOW[b]
    if b == 0x7F:
        return "⌂"
    return bytes([b]).decode("cp437")


def main():
    src, dst = sys.argv[1], sys.argv[2]
    glyphs, table, height = load_psf1(src)
    assert height == 16
    missing = []
    rows = []
    for b in range(256):
        ch = cp437_char(b)
        g = table.get(ord(ch)) if b else table.get(0x20)
        if g is None:
            missing.append(b)
            data = bytes(16)
        else:
            data = glyphs[g]
        if g is None and b in SYNTH:
            data = SYNTH[b]
            missing.remove(b)
        rows.append("    " + ", ".join(f"0x{x:02x}" for x in data) + f",  /* {b:02X} */")
    with open(dst, "w") as f:
        f.write("/* Generated by tools/psf2c.py from Terminus (SIL OFL 1.1), CP437 order. Do not edit. */\n")
        f.write('#include "font8x16.h"\n\n')
        f.write("const uint8_t font8x16[256][16] = {\n")
        f.write("\n".join(rows) + "\n};\n")
    print(f"wrote {dst}; missing glyphs (blank): {[hex(m) for m in missing]}")


if __name__ == "__main__":
    main()
